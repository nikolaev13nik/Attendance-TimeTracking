CREATE TABLE att_work_sessions (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY,
    tenant_id          INTEGER                  NOT NULL,
    user_id            INTEGER,
    updated_by         VARCHAR(255),
    sys_update_date    TIMESTAMP(6) WITH TIME ZONE,
    status             VARCHAR(255),
    work_date          DATE,
    open_session_date  TIMESTAMP(6) WITH TIME ZONE,
    close_session_date TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_att_work_sessions PRIMARY KEY (id)
);

CREATE INDEX ix_att_work_sessions_tenant_user_date ON att_work_sessions (tenant_id, user_id, work_date);
CREATE INDEX ix_att_work_sessions_tenant_date ON att_work_sessions (tenant_id, work_date);

CREATE TABLE att_month_statistic (
    tenant_id        INTEGER          NOT NULL,
    user_id          INTEGER          NOT NULL,
    month_start_date DATE             NOT NULL,
    work_days        INTEGER          NOT NULL,
    overtime_hours   DOUBLE PRECISION NOT NULL,
    total_work_hours DOUBLE PRECISION NOT NULL,
    vacation_days    DOUBLE PRECISION,
    sick_days        DOUBLE PRECISION,
    updated_by       VARCHAR(255),
    sys_update_date  TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_att_month_statistic PRIMARY KEY (tenant_id, user_id, month_start_date)
);

CREATE TABLE att_user_leave_days (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY,
    tenant_id       INTEGER          NOT NULL,
    user_id         INTEGER          NOT NULL,
    leave_date      DATE             NOT NULL,
    vacation_amount DOUBLE PRECISION,
    sick_amount     DOUBLE PRECISION,
    updated_by      VARCHAR(255),
    sys_update_date TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_att_user_leave_days PRIMARY KEY (id),
    CONSTRAINT uq_att_user_leave_days UNIQUE (tenant_id, user_id, leave_date)
);

CREATE INDEX ix_att_user_leave_days_tenant_date ON att_user_leave_days (tenant_id, leave_date);
