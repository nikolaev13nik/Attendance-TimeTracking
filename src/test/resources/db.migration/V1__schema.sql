CREATE TABLE att_work_sessions
(
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
    tenant_id          INTEGER                                              NOT NULL,
    user_id            INTEGER,
    updated_by         VARCHAR(255),
    sys_update_date    TIMESTAMP(6) WITH TIME ZONE,
    status             VARCHAR(10),
    work_date          DATE,
    open_session_date  TIMESTAMP(6) WITH TIME ZONE,
    close_session_date TIMESTAMP(6) WITH TIME ZONE,
                       PRIMARY KEY (id)
);

